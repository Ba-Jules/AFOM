function readLocal(key: string): string | null {
  try { return localStorage.getItem(key); } catch { return null; }
}
function writeLocal(key: string, value: string) {
  try { localStorage.setItem(key, value); } catch { /* volontairement silencieux */ }
}
export function initialLang(): Lang { return readLocal(LANG_KEY) === "en" ? "en" : "fr"; }
export function initialTheme(): Theme { return readLocal(THEME_KEY) === "dark" ? "dark" : "light"; }
export function storeLang(lang: Lang) { writeLocal(LANG_KEY, lang); }
export function storeTheme(theme: Theme) { writeLocal(THEME_KEY, theme); }

