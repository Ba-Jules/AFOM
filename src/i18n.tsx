const dicts: Record<Lang, Dict> = { fr, en };

function resolve(dict: Dict, path: string): Leaf | undefined {
  let current: Leaf | Dict | undefined = dict;
  for (const part of path.split(".")) {
    if (typeof current !== "object") return undefined;
    current = (current as Dict)[part];
  }
  return current as Leaf | undefined;
}

export function translate(lang: Lang, key: string, vars: Vars = {}): string {
  const leaf = resolve(dicts[lang], key) ?? resolve(dicts.fr, key);
  if (leaf === undefined || Array.isArray(leaf)) return key;
  return typeof leaf === "function" ? leaf(vars) : leaf;
}

export function translateList(lang: Lang, key: string): string[] {
  const leaf = resolve(dicts[lang], key) ?? resolve(dicts.fr, key);
  return Array.isArray(leaf) ? leaf : [];
}

interface PreferencesValue { lang: Lang; theme: Theme; t: (key: string, vars?: Vars) => string; setLang: (lang: Lang) => void; setTheme: (theme: Theme) => void; }

const PreferencesContext = createContext<PreferencesValue | null>(null);

export function PreferencesProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => initialLang());
  const [theme, setThemeState] = useState<Theme>(() => initialTheme());
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  useEffect(() => { document.documentElement.dataset.theme = theme; }, [theme]);
  function setLang(next: Lang) { setLangState(next); storeLang(next); }
  function setTheme(next: Theme) { setThemeState(next); storeTheme(next); }
  const t = (key: string, vars?: Vars) => translate(lang, key, vars);
  return <PreferencesContext.Provider value={{ lang, theme, t, setLang, setTheme }}>{children}</PreferencesContext.Provider>;
}

export function usePreferences(): PreferencesValue {
  const value = useContext(PreferencesContext);
  if (!value) throw new Error("usePreferences must be used within PreferencesProvider");
  return value;
}

